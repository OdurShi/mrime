"""CEC2017 / CEC2022 through the reference C sources shipped in ``matlab/``.

``matlab/cec17_func.cpp`` and ``matlab/cec22_func.cpp`` are the MEX sources the author's MATLAB
experiments call. They are compiled here *unmodified*: a generated translation unit includes
the source file after a stub ``mex.h`` and exports one C function that evaluates a block of
points. The benchmark values are therefore those of the reference implementation, not of a
re-implementation. A C++ compiler (``c++``, ``g++`` or ``clang++``, or ``$CXX``) is required.

The benchmark definition data (rotation matrices, shift vectors, shuffle indices) are the files
in ``matlab/input_data`` and ``matlab/input_data22``; they are documented in ``data/README.md``.

Environment variables:
    ``MRIME_CEC_SOURCE_DIR``: directory holding the two ``.cpp`` files and the
        ``input_data`` / ``input_data22`` folders (default: the ``matlab/`` folder of the
        source checkout). The command-line option ``--data-dir`` sets the same thing.
    ``MRIME_NATIVE_BUILD_DIR``: where the shared libraries are built (default:
        ``.mrime_native/`` next to the source directory).
    ``CXX``: compiler to use.
"""

from __future__ import annotations

import ctypes
import hashlib
import logging
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from functools import cache
from pathlib import Path

import numpy as np

logger = logging.getLogger(__name__)


class NativeBackendError(RuntimeError):
    """The reference C sources could not be located, compiled or loaded."""


@dataclass(frozen=True)
class _NativeSuite:
    source: str
    entry: str
    data_dir: str


_SUITES: dict[str, _NativeSuite] = {
    "cec2017": _NativeSuite("cec17_func.cpp", "cec17_test_func", "input_data"),
    "cec2022": _NativeSuite("cec22_func.cpp", "cec22_test_func", "input_data22"),
}

_MEX_STUB = """\
#ifndef MRIME_MEX_STUB_H
#define MRIME_MEX_STUB_H
#include <stddef.h>
#include <stdlib.h>
typedef struct mxArray_tag mxArray;
typedef enum { mxREAL = 0 } mxComplexity;
int mexPrintf(const char *, ...);
void mexErrMsgTxt(const char *);
size_t mxGetM(const mxArray *);
size_t mxGetN(const mxArray *);
double *mxGetPr(const mxArray *);
mxArray *mxCreateDoubleMatrix(size_t, size_t, mxComplexity);
#endif
"""

_MALLOC_STUB = "#include <stdlib.h>\n"

_SHIM_TEMPLATE = """\
// Generated by mrime.benchmarks.native. Compiles the reference CEC source unmodified.
#include <stddef.h>
#include <stdlib.h>
#if defined(_WIN32)
#include <direct.h>
#define MRIME_CHDIR _chdir
#define MRIME_GETCWD _getcwd
#else
#include <unistd.h>
#define MRIME_CHDIR chdir
#define MRIME_GETCWD getcwd
#endif
#include "{source}"

int mexPrintf(const char *, ...) {{ return 0; }}
void mexErrMsgTxt(const char *) {{}}
size_t mxGetM(const mxArray *) {{ return 0; }}
size_t mxGetN(const mxArray *) {{ return 0; }}
double *mxGetPr(const mxArray *) {{ return NULL; }}
mxArray *mxCreateDoubleMatrix(size_t, size_t, mxComplexity) {{ return NULL; }}

static int mrime_loaded_func = -1;
static int mrime_loaded_dim = -1;

// The reference code opens its data files relative to the working directory, and only when
// the (function, dimension) pair changes; the directory is switched for that call only.
extern "C" int mrime_cec_eval(const char *data_root, double *x, double *f, int nx, int mx,
                              int func_num) {{
    if (func_num == mrime_loaded_func && nx == mrime_loaded_dim) {{
        {entry}(x, f, nx, mx, func_num);
        return 0;
    }}
    char previous[4096];
    if (MRIME_GETCWD(previous, sizeof(previous)) == NULL) return 1;
    if (MRIME_CHDIR(data_root) != 0) return 2;
    {entry}(x, f, nx, mx, func_num);
    if (MRIME_CHDIR(previous) != 0) return 3;
    mrime_loaded_func = func_num;
    mrime_loaded_dim = nx;
    return 0;
}}
"""


def default_source_dir() -> Path:
    """Locate the directory with the reference C sources and data."""
    env = os.environ.get("MRIME_CEC_SOURCE_DIR")
    if env:
        return Path(env).expanduser().resolve()
    for parent in Path(__file__).resolve().parents:
        candidate = parent / "matlab"
        if (candidate / _SUITES["cec2017"].source).is_file():
            return candidate
    raise NativeBackendError(
        "cannot find the reference CEC sources; run from a source checkout of the repository "
        "or set MRIME_CEC_SOURCE_DIR to the folder containing cec17_func.cpp, cec22_func.cpp, "
        "input_data/ and input_data22/"
    )


def find_compiler() -> str:
    """Return the C++ compiler to use, or raise :class:`NativeBackendError`."""
    candidates = [os.environ.get("CXX"), "c++", "g++", "clang++"]
    for name in candidates:
        if name and shutil.which(name):
            return shutil.which(name)
    raise NativeBackendError(
        "no C++ compiler found (tried $CXX, c++, g++, clang++); install one or use "
        "backend='opfunu'"
    )


def _library_suffix() -> str:
    if sys.platform == "darwin":
        return ".dylib"
    if sys.platform.startswith("win"):
        return ".dll"
    return ".so"


def _default_build_dir(source_dir: Path) -> Path:
    env = os.environ.get("MRIME_NATIVE_BUILD_DIR")
    if env:
        return Path(env).expanduser().resolve()
    preferred = source_dir.parent / ".mrime_native"
    try:
        preferred.mkdir(parents=True, exist_ok=True)
        return preferred
    except OSError:
        return Path(tempfile.gettempdir()) / "mrime_native"


def build_library(
    suite: str, source_dir: Path | None = None, build_dir: Path | None = None
) -> Path:
    """Compile the reference source of ``suite`` into a shared library and return its path.

    The library is rebuilt only when the source, the shim or the compiler changes (the file
    name carries a digest of all three).
    """
    if suite not in _SUITES:
        raise ValueError(f"no native backend for suite {suite!r}")
    spec = _SUITES[suite]
    source_dir = (source_dir or default_source_dir()).resolve()
    source = source_dir / spec.source
    if not source.is_file():
        raise NativeBackendError(f"reference source not found: {source}")
    build_dir = build_dir or _default_build_dir(source_dir)
    build_dir.mkdir(parents=True, exist_ok=True)
    compiler = find_compiler()

    escaped = str(source).replace("\\", "\\\\").replace('"', '\\"')
    shim = _SHIM_TEMPLATE.format(source=escaped, entry=spec.entry)
    digest = hashlib.sha256(source.read_bytes() + shim.encode() + compiler.encode()).hexdigest()
    library = build_dir / f"mrime_{suite}_{digest[:12]}{_library_suffix()}"
    if library.is_file():
        return library

    stub_dir = build_dir / "stub"
    stub_dir.mkdir(exist_ok=True)
    (stub_dir / "mex.h").write_text(_MEX_STUB)
    (stub_dir / "malloc.h").write_text(_MALLOC_STUB)
    shim_path = build_dir / f"shim_{suite}_{digest[:12]}.cpp"
    shim_path.write_text(shim)
    partial = library.with_name(f"{library.name}.{os.getpid()}.tmp")
    command = [
        compiler, "-O2", "-ffp-contract=off", "-shared", "-fPIC", "-w",
        "-I", str(stub_dir), "-o", str(partial), str(shim_path),
    ]
    logger.info("building native %s backend: %s", suite, " ".join(command))
    completed = subprocess.run(command, capture_output=True, text=True, check=False)
    if completed.returncode != 0 or not partial.is_file():
        raise NativeBackendError(
            f"compiling {source.name} failed (exit {completed.returncode}):\n{completed.stderr}"
        )
    os.replace(partial, library)
    return library


class NativeSuite:
    """A loaded reference library for one suite."""

    def __init__(
        self, suite: str, source_dir: Path | None = None, build_dir: Path | None = None
    ) -> None:
        self.suite = suite
        self.source_dir = (source_dir or default_source_dir()).resolve()
        self.data_dir = self.source_dir / _SUITES[suite].data_dir
        library = build_library(suite, self.source_dir, build_dir)
        try:
            self._lib = ctypes.CDLL(str(library))
        except OSError as error:
            raise NativeBackendError(f"cannot load {library}: {error}") from error
        self._lib.mrime_cec_eval.argtypes = [
            ctypes.c_char_p,
            ctypes.POINTER(ctypes.c_double),
            ctypes.POINTER(ctypes.c_double),
            ctypes.c_int,
            ctypes.c_int,
            ctypes.c_int,
        ]
        self._lib.mrime_cec_eval.restype = ctypes.c_int
        self._root = os.fsencode(str(self.source_dir))

    def has_data(self, func_num: int, dim: int, needs_shuffle: bool) -> bool:
        """Whether the data files of ``(func_num, dim)`` exist (the C code does not check)."""
        files = [f"M_{func_num}_D{dim}.txt", f"shift_data_{func_num}.txt"]
        if needs_shuffle:
            files.append(f"shuffle_data_{func_num}_D{dim}.txt")
        return all((self.data_dir / name).is_file() for name in files)

    def evaluate(self, points: np.ndarray, func_num: int) -> np.ndarray:
        """Reference objective values of the rows of ``points`` for function ``func_num``."""
        block = np.array(points, dtype=np.float64, order="C", ndmin=2)
        m, dim = block.shape
        values = np.empty(m, dtype=np.float64)
        code = self._lib.mrime_cec_eval(
            self._root,
            block.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
            values.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
            dim,
            m,
            func_num,
        )
        if code != 0:
            raise NativeBackendError(f"reference code could not switch directory (code {code})")
        return values


@cache
def _load_suite(suite: str, source_dir: str) -> NativeSuite:
    return NativeSuite(suite, Path(source_dir))


def load_suite(suite: str, source_dir: Path | None = None) -> NativeSuite:
    """Build (if needed) and load the reference library of ``suite``.

    ``source_dir`` defaults to :func:`default_source_dir` (the ``matlab/`` folder of the
    checkout, or ``$MRIME_CEC_SOURCE_DIR``). Loaded libraries are cached per process and
    directory.
    """
    directory = (source_dir or default_source_dir()).resolve()
    return _load_suite(suite, str(directory))
